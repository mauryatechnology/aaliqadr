/**
 * Generates src/app/zodiac-tokens.css from src/config/zodiac.ts so the twelve themes have a
 * single source of truth. Runs automatically before `dev` and `build` (package.json).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SIGNS } from "../src/config/zodiac";

const out = fileURLToPath(new URL("../src/app/zodiac-tokens.css", import.meta.url));

const blocks = SIGNS.map(({ slug, element, theme: t }) => {
  const vars = {
    "--z-bg": t.bg,
    "--z-surface": t.surface,
    "--z-primary": t.primary,
    "--z-secondary": t.secondary,
    "--z-accent": t.accent,
    "--z-text": t.text,
    "--z-muted": t.muted,
    "--z-on-primary": t.onPrimary,
    "--z-glow": t.glow,
    "--z-g1": t.gradient[0],
    "--z-g2": t.gradient[1],
    "--z-g3": t.gradient[2],
  };
  const body = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n");
  // A page-level scope (<ZodiacScope page>) themes the whole document: header, backdrop, body.
  return `/* ${slug} (${element}) */\n[data-zodiac="${slug}"],\n:root:has(.zodiac-page[data-zodiac="${slug}"]) {\n${body}\n}`;
});

writeFileSync(
  out,
  `/* GENERATED by scripts/generate-zodiac-css.ts from src/config/zodiac.ts. Do not edit. */\n\n${blocks.join("\n\n")}\n`,
);
console.log(`zodiac-tokens.css: ${SIGNS.length} themes`);
